-- Busca por qualquer código: interno atual, interno antigo ou da loja
CREATE VIEW vw_busca_codigo AS
SELECT p.codigo AS codigo, p.id AS produto_id, 'INTERNO' AS origem, NULL::BIGINT AS fornecedor_id
FROM produtos p
UNION ALL
SELECT h.codigo, h.produto_id, 'INTERNO_ANTIGO', NULL
FROM produto_codigos_historico h
UNION ALL
SELECT f.codigo_fornecedor, f.produto_id, 'FORNECEDOR', f.fornecedor_id
FROM produto_codigos_fornecedor f;

-- Cada peça com o código da etiqueta e a situação, que vem da ÚLTIMA movimentação dela:
--   ENTRADA, CANCELAMENTO_VENDA, DEVOLUCAO_CLIENTE, AJUSTE -> DISPONIVEL
--   VENDA -> VENDIDA   |   PERDA -> PERDIDA   |   DEVOLUCAO_FORNECEDOR -> DEVOLVIDA
-- Vender pelo modelo (FIFO): o back pega a primeira peça
--   WHERE produto_id = ? AND situacao = 'DISPONIVEL'
--   ORDER BY maleta_data_entrada, maleta_id, numero
CREATE VIEW vw_pecas AS
SELECT  pc.id                                    AS peca_id,
        p.codigo || '-' || lpad(pc.numero::text, greatest(2, length(pc.numero::text)), '0') AS codigo,
        pc.produto_id,
        pc.numero,
        pc.maleta_item_id,
        mi.maleta_id,
        m.data_entrada                           AS maleta_data_entrada,
        CASE WHEN ult.tipo IS NULL                    THEN 'SEM_ENTRADA'
             WHEN ult.tipo = 'VENDA'                  THEN 'VENDIDA'
             WHEN ult.tipo = 'PERDA'                  THEN 'PERDIDA'
             WHEN ult.tipo = 'DEVOLUCAO_FORNECEDOR'   THEN 'DEVOLVIDA'
             ELSE 'DISPONIVEL' END               AS situacao,
        ult.tipo                                 AS ultima_movimentacao,
        ult.venda_id                             AS ultima_venda_id,
        ult.criado_em                            AS ultima_movimentacao_em
FROM pecas pc
JOIN produtos     p  ON p.id  = pc.produto_id
JOIN maleta_itens mi ON mi.id = pc.maleta_item_id
JOIN maletas      m  ON m.id  = mi.maleta_id
LEFT JOIN LATERAL (
        SELECT mv.tipo, mv.venda_id, mv.criado_em
        FROM movimentacoes_estoque mv
        WHERE mv.peca_id = pc.id
        ORDER BY mv.id DESC
        LIMIT 1
) ult ON TRUE;

-- Que peça é essa etiqueta? Aceita o código atual (C0001-02) e o antigo, de antes
-- de o produto mudar de categoria (INTERNO_ANTIGO).
CREATE VIEW vw_busca_peca AS
SELECT  b.codigo || '-' || lpad(pc.numero::text, greatest(2, length(pc.numero::text)), '0') AS codigo,
        pc.id          AS peca_id,
        pc.produto_id,
        b.origem
FROM pecas pc
JOIN (SELECT id AS produto_id, codigo, 'INTERNO' AS origem FROM produtos
      UNION ALL
      SELECT produto_id, codigo, 'INTERNO_ANTIGO' FROM produto_codigos_historico) b
  ON b.produto_id = pc.produto_id;

-- Saldo, situação e atraso de cada parcela de venda FINALIZADA
CREATE VIEW vw_saldo_parcelas AS
SELECT  p.id                                   AS parcela_id,
        p.venda_id,
        v.cliente_id,
        p.numero_parcela,
        p.valor                                AS valor_parcela,
        COALESCE(pg.total_pago, 0)             AS total_pago,
        p.valor - COALESCE(pg.total_pago, 0)   AS saldo,
        p.data_vencimento,
        pg.ultimo_pagamento,
        CASE WHEN p.valor - COALESCE(pg.total_pago, 0) <= 0 THEN 'PAGA'
             WHEN COALESCE(pg.total_pago, 0) > 0            THEN 'PARCIAL'
             ELSE 'PENDENTE' END               AS situacao,
        (p.valor - COALESCE(pg.total_pago, 0) > 0
             AND p.data_vencimento < CURRENT_DATE)         AS atrasada,
        CASE WHEN p.valor - COALESCE(pg.total_pago, 0) > 0
                  AND p.data_vencimento < CURRENT_DATE
             THEN CURRENT_DATE - p.data_vencimento ELSE 0 END AS dias_atraso
FROM parcelas p
JOIN vendas   v ON v.id = p.venda_id
LEFT JOIN LATERAL (
        SELECT SUM(pa.valor) AS total_pago, MAX(pa.data_pagamento) AS ultimo_pagamento
        FROM pagamentos pa
        WHERE pa.parcela_id = p.id AND NOT pa.estornado
) pg ON TRUE
WHERE p.status = 'ATIVA'
  AND v.status = 'FINALIZADA';

-- Posição financeira de cada cliente (alimenta rankings e tela de cobrança)
CREATE VIEW vw_saldo_clientes AS
WITH compras AS (
    SELECT cliente_id, SUM(valor_total) AS total_comprado, COUNT(*) AS qtd_vendas,
           MAX(data_venda) AS ultima_compra
    FROM vendas WHERE status = 'FINALIZADA'
    GROUP BY cliente_id
), fin AS (
    SELECT cliente_id,
           SUM(total_pago)                                AS total_pago,
           SUM(saldo)                                     AS total_em_aberto,
           SUM(saldo) FILTER (WHERE atrasada)             AS total_atrasado,
           COUNT(*)   FILTER (WHERE atrasada)             AS qtd_parcelas_atrasadas,
           MAX(dias_atraso)                               AS maior_dias_atraso,
           MIN(data_vencimento) FILTER (WHERE saldo > 0)  AS vencimento_mais_antigo_em_aberto,
           MAX(ultimo_pagamento)                          AS ultimo_pagamento
    FROM vw_saldo_parcelas
    GROUP BY cliente_id
)
SELECT  c.id                                    AS cliente_id,
        c.nome,
        c.telefone,
        COALESCE(co.qtd_vendas, 0)              AS qtd_vendas,
        COALESCE(co.total_comprado, 0)          AS total_comprado,
        COALESCE(f.total_pago, 0)               AS total_pago,
        COALESCE(f.total_em_aberto, 0)          AS total_em_aberto,
        COALESCE(f.total_atrasado, 0)           AS total_atrasado,
        COALESCE(f.qtd_parcelas_atrasadas, 0)   AS qtd_parcelas_atrasadas,
        COALESCE(f.maior_dias_atraso, 0)        AS maior_dias_atraso,
        f.vencimento_mais_antigo_em_aberto,
        co.ultima_compra,
        f.ultimo_pagamento,
        -- "há quanto tempo sem pagar": só faz sentido para quem deve algo
        CASE WHEN COALESCE(f.total_em_aberto, 0) > 0
             THEN CURRENT_DATE - COALESCE(f.ultimo_pagamento, co.ultima_compra) END AS dias_sem_pagar
FROM clientes c
LEFT JOIN compras co ON co.cliente_id = c.id
LEFT JOIN fin     f  ON f.cliente_id  = c.id;

-- Números gerais do dashboard (uma linha)
CREATE VIEW vw_resumo_financeiro AS
SELECT  (SELECT COALESCE(SUM(valor_total), 0) FROM vendas WHERE status = 'FINALIZADA') AS total_vendido,
        COALESCE(SUM(total_pago), 0)                                     AS total_recebido,
        COALESCE(SUM(saldo), 0)                                          AS total_a_receber,
        COALESCE(SUM(saldo) FILTER (WHERE atrasada), 0)                  AS total_atrasado,
        COUNT(DISTINCT cliente_id) FILTER (WHERE saldo > 0)              AS clientes_devendo,
        COUNT(DISTINCT cliente_id) FILTER (WHERE atrasada)               AS clientes_atrasados
FROM vw_saldo_parcelas;

-- Estoque por item de maleta (quanto ainda resta de cada remessa).
-- Para saber QUAIS peças restam, use vw_pecas.
CREATE VIEW vw_estoque_maleta_itens AS
SELECT  mi.id            AS maleta_item_id,
        mi.maleta_id,
        mi.produto_id,
        mi.quantidade    AS quantidade_recebida,
        COALESCE(SUM(m.quantidade), 0)::INTEGER AS quantidade_disponivel
FROM maleta_itens mi
LEFT JOIN movimentacoes_estoque m ON m.maleta_item_id = mi.id
GROUP BY mi.id;

-- Produtos com situação de estoque (DISPONIVEL / BAIXO / ESGOTADO calculados)
CREATE VIEW vw_produtos_estoque AS
SELECT  p.id AS produto_id, p.codigo, p.nome, p.categoria_id, p.preco_venda,
        p.quantidade_estoque, p.estoque_minimo,
        CASE WHEN p.quantidade_estoque = 0                THEN 'ESGOTADO'
             WHEN p.quantidade_estoque <= p.estoque_minimo THEN 'BAIXO'
             ELSE 'DISPONIVEL' END AS situacao_estoque
FROM produtos p
WHERE p.status = 'ATIVO';

-- Dashboard por maleta.
-- Pagamento é por parcela (da venda inteira), não por peça. Para atribuir "pago" e
-- "em aberto" a uma maleta, o valor é RATEADO pela participação do item na venda.
-- O acréscimo e o desconto entram no rateio porque valor_total já os inclui.
CREATE VIEW vw_dashboard_maletas AS
WITH venda_fin AS (
    SELECT v.id AS venda_id, v.valor_produtos, v.valor_total,
           COALESCE(SUM(sp.total_pago), 0) AS pago,
           COALESCE(SUM(sp.saldo), 0)      AS aberto
    FROM vendas v
    LEFT JOIN vw_saldo_parcelas sp ON sp.venda_id = v.id
    WHERE v.status = 'FINALIZADA'
    GROUP BY v.id
), itens AS (
    SELECT mi.maleta_id,
           iv.quantidade,
           iv.subtotal * vf.valor_total / NULLIF(vf.valor_produtos, 0) AS valor_liquido,
           iv.subtotal * vf.pago        / NULLIF(vf.valor_produtos, 0) AS valor_pago,
           iv.subtotal * vf.aberto      / NULLIF(vf.valor_produtos, 0) AS valor_aberto
    FROM itens_venda iv
    JOIN venda_fin   vf ON vf.venda_id = iv.venda_id
    JOIN maleta_itens mi ON mi.id = iv.maleta_item_id
), recebido AS (
    SELECT maleta_id,
           SUM(quantidade_recebida)   AS quantidade_recebida,
           SUM(quantidade_disponivel) AS quantidade_disponivel,
           COUNT(DISTINCT produto_id) AS produtos_distintos
    FROM vw_estoque_maleta_itens GROUP BY maleta_id
), custo AS (
    SELECT maleta_id, SUM(quantidade * preco_custo) AS custo_total
    FROM maleta_itens GROUP BY maleta_id
), vendido AS (
    SELECT maleta_id,
           SUM(quantidade)             AS quantidade_vendida,
           ROUND(SUM(valor_liquido), 2) AS valor_vendido,
           ROUND(SUM(valor_pago), 2)    AS valor_pago,
           ROUND(SUM(valor_aberto), 2)  AS valor_em_aberto
    FROM itens GROUP BY maleta_id
)
SELECT  m.id AS maleta_id, m.codigo, m.nome, m.tipo, m.status, m.data_entrada,
        COALESCE(r.produtos_distintos, 0)    AS produtos_distintos,
        COALESCE(r.quantidade_recebida, 0)   AS quantidade_recebida,
        COALESCE(r.quantidade_disponivel, 0) AS quantidade_disponivel,
        COALESCE(vd.quantidade_vendida, 0)   AS quantidade_vendida,
        COALESCE(c.custo_total, 0)           AS custo_total,
        COALESCE(vd.valor_vendido, 0)        AS valor_vendido,
        COALESCE(vd.valor_pago, 0)           AS valor_pago,
        COALESCE(vd.valor_em_aberto, 0)      AS valor_em_aberto
FROM maletas m
LEFT JOIN recebido r  ON r.maleta_id  = m.id
LEFT JOIN custo    c  ON c.maleta_id  = m.id
LEFT JOIN vendido  vd ON vd.maleta_id = m.id;

-- Auditoria: produtos cujo cache de estoque diverge do histórico (deve vir sempre vazia)
CREATE VIEW vw_divergencia_estoque AS
SELECT p.id AS produto_id, p.codigo, p.quantidade_estoque AS estoque_cache,
       COALESCE(SUM(m.quantidade), 0) AS estoque_historico
FROM produtos p
LEFT JOIN movimentacoes_estoque m ON m.produto_id = p.id
GROUP BY p.id
HAVING p.quantidade_estoque <> COALESCE(SUM(m.quantidade), 0);


