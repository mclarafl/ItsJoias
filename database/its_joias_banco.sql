SET timezone TO 'America/Sao_Paulo';

-- =====================================================================
-- PARTE 1 — TABELAS
-- =====================================================================

-- ---------------------------------------------------------------------
-- usuarios
-- ---------------------------------------------------------------------
CREATE TABLE usuarios (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(120) NOT NULL,
    email          VARCHAR(160) NOT NULL,
    senha_hash     VARCHAR(255) NOT NULL,
    ativo          BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
-- e-mail único sem diferenciar maiúsculas/minúsculas
CREATE UNIQUE INDEX uq_usuarios_email ON usuarios (lower(email));

-- ---------------------------------------------------------------------
-- clientes  (sem total_devido / total_pago / total_comprado: são calculados)
-- ---------------------------------------------------------------------
CREATE TABLE clientes (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(120) NOT NULL,
    telefone       VARCHAR(13)  NOT NULL,          -- só dígitos: DDD + número (ou 55 + DDD + número)
    email          VARCHAR(160),
    cpf            VARCHAR(11),                    -- só dígitos (exatamente 11, pelo CHECK)
    endereco       TEXT,
    observacoes    TEXT,
    ativo          BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_clientes_nome     CHECK (btrim(nome) <> ''),
    CONSTRAINT ck_clientes_telefone CHECK (telefone ~ '^[0-9]{10,13}$'),
    CONSTRAINT ck_clientes_cpf      CHECK (cpf IS NULL OR cpf ~ '^[0-9]{11}$')
);
CREATE UNIQUE INDEX uq_clientes_cpf      ON clientes (cpf) WHERE cpf IS NOT NULL;
CREATE INDEX        ix_clientes_nome     ON clientes (lower(nome));
CREATE INDEX        ix_clientes_telefone ON clientes (telefone);

-- ---------------------------------------------------------------------
-- fornecedores  (a loja/fábrica de onde vêm as maletas)
-- ---------------------------------------------------------------------
CREATE TABLE fornecedores (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(120) NOT NULL,
    telefone       VARCHAR(13),
    observacao     TEXT,
    ativo          BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_fornecedores_nome ON fornecedores (lower(nome));

-- ---------------------------------------------------------------------
-- categorias
-- prefixo: letra(s) que abrem o código interno (C = colar, A = anel...)
-- proximo_numero: contador próprio de cada categoria (C0001, C0002... / A0001...)
-- ---------------------------------------------------------------------
CREATE TABLE categorias (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(60) NOT NULL,
    prefixo         VARCHAR(3)  NOT NULL,
    proximo_numero  INTEGER     NOT NULL DEFAULT 1,
    descricao       TEXT,
    ativo           BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_categorias_prefixo UNIQUE (prefixo),
    CONSTRAINT ck_categorias_prefixo CHECK (prefixo ~ '^[A-Z]{1,3}$'),
    CONSTRAINT ck_categorias_numero  CHECK (proximo_numero > 0)
);
CREATE UNIQUE INDEX uq_categorias_nome ON categorias (lower(nome));

-- ---------------------------------------------------------------------
-- categoria_palavras_chave  (dicionário que o back usa para ler a descrição)
-- termo sempre minúsculo e sem acento: "gargantilha", "alianca", "ear cuff"
-- prioridade maior vence (ex.: "conjunto"/"kit" ganham de "colar" e "brinco")
-- ---------------------------------------------------------------------
CREATE TABLE categoria_palavras_chave (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id  BIGINT      NOT NULL REFERENCES categorias (id) ON DELETE CASCADE,
    termo         VARCHAR(40) NOT NULL,
    prioridade    SMALLINT    NOT NULL DEFAULT 1,
    CONSTRAINT uq_palavras_termo  UNIQUE (termo),
    CONSTRAINT ck_palavras_termo  CHECK (termo ~ '^[a-z0-9]+( [a-z0-9]+)*$'),
    CONSTRAINT ck_palavras_prior  CHECK (prioridade >= 0)
);
CREATE INDEX ix_palavras_categoria ON categoria_palavras_chave (categoria_id);

-- ---------------------------------------------------------------------
-- produtos  = CATÁLOGO (o "modelo" da peça), não a remessa.
-- quantidade_estoque é um cache do total; o histórico está em movimentacoes_estoque.
-- O código é preenchido pela trigger trg_produtos_codigo (Parte 3).
-- ---------------------------------------------------------------------
CREATE TABLE produtos (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo              VARCHAR(10)   NOT NULL,                 -- interno, gerado pelo banco: C0042, A0007
    nome                VARCHAR(120)  NOT NULL,
    descricao           TEXT,
    categoria_id        BIGINT        NOT NULL REFERENCES categorias (id) ON DELETE RESTRICT,
    preco_custo         NUMERIC(12,2) NOT NULL DEFAULT 0,       -- custo de referência (o real fica em maleta_itens)
    preco_venda         NUMERIC(12,2) NOT NULL,                 -- preço ATUAL de tabela
    quantidade_estoque  INTEGER       NOT NULL DEFAULT 0,
    estoque_minimo      INTEGER       NOT NULL DEFAULT 0,
    status              VARCHAR(10)   NOT NULL DEFAULT 'ATIVO',
    versao              INTEGER       NOT NULL DEFAULT 0,       -- @Version (lock otimista do JPA)
    criado_em           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    atualizado_em       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_produtos_codigo          UNIQUE (codigo),
    CONSTRAINT ck_produtos_codigo          CHECK (codigo ~ '^[A-Z]{1,3}[0-9]{4,}$'),
    CONSTRAINT ck_produtos_preco_custo     CHECK (preco_custo >= 0),
    CONSTRAINT ck_produtos_preco_venda     CHECK (preco_venda >= 0),
    CONSTRAINT ck_produtos_estoque         CHECK (quantidade_estoque >= 0),
    CONSTRAINT ck_produtos_estoque_minimo  CHECK (estoque_minimo >= 0),
    CONSTRAINT ck_produtos_status          CHECK (status IN ('ATIVO', 'INATIVO'))
);
-- uq_produtos_codigo já cria o índice de "codigo"; não crie outro.
CREATE INDEX ix_produtos_nome      ON produtos (lower(nome));
CREATE INDEX ix_produtos_categoria ON produtos (categoria_id);

-- ---------------------------------------------------------------------
-- produto_codigos_fornecedor  ("de-para": código da loja -> nosso produto)
-- É o que faz o mesmo item, numa maleta nova, cair no MESMO produto.
-- ---------------------------------------------------------------------
CREATE TABLE produto_codigos_fornecedor (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id            BIGINT      NOT NULL REFERENCES produtos     (id) ON DELETE RESTRICT,
    fornecedor_id         BIGINT      NOT NULL REFERENCES fornecedores (id) ON DELETE RESTRICT,
    codigo_fornecedor     VARCHAR(40) NOT NULL,   -- sempre MAIÚSCULO e sem espaços nas pontas
    descricao_fornecedor  TEXT,                   -- descrição da 1ª vez que o código apareceu
    criado_em             TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_pcf_fornecedor_codigo UNIQUE (fornecedor_id, codigo_fornecedor),
    CONSTRAINT ck_pcf_codigo CHECK (codigo_fornecedor <> '' AND codigo_fornecedor = upper(btrim(codigo_fornecedor)))
);
CREATE INDEX ix_pcf_produto ON produto_codigos_fornecedor (produto_id);
-- busca pela etiqueta da loja sem saber o fornecedor (vw_busca_codigo)
CREATE INDEX ix_pcf_codigo  ON produto_codigos_fornecedor (codigo_fornecedor);

-- ---------------------------------------------------------------------
-- produto_codigos_historico  (códigos antigos, se a categoria for corrigida)
-- Etiqueta velha continua sendo encontrada na busca.
-- ---------------------------------------------------------------------
CREATE TABLE produto_codigos_historico (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id      BIGINT      NOT NULL REFERENCES produtos (id) ON DELETE RESTRICT,
    codigo          VARCHAR(10) NOT NULL,
    substituido_em  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_pch_codigo UNIQUE (codigo)
);
CREATE INDEX ix_pch_produto ON produto_codigos_historico (produto_id);

-- ---------------------------------------------------------------------
-- maletas  = REMESSA / LOTE (Maleta Janeiro, Maleta Fevereiro...)
-- ---------------------------------------------------------------------
CREATE TABLE maletas (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo         VARCHAR(20)  NOT NULL,
    nome           VARCHAR(120) NOT NULL,
    fornecedor_id  BIGINT       NOT NULL REFERENCES fornecedores (id) ON DELETE RESTRICT,
    tipo           VARCHAR(10)  NOT NULL,
    data_entrada   DATE         NOT NULL DEFAULT CURRENT_DATE,
    status         VARCHAR(12)  NOT NULL DEFAULT 'ATIVA',
    observacao     TEXT,
    criado_em      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_maletas_codigo UNIQUE (codigo),
    CONSTRAINT ck_maletas_tipo   CHECK (tipo   IN ('NOVA', 'ANTIGA')),
    CONSTRAINT ck_maletas_status CHECK (status IN ('ATIVA', 'ENCERRADA'))
);
CREATE INDEX ix_maletas_fornecedor ON maletas (fornecedor_id);

-- ---------------------------------------------------------------------
-- maleta_itens  (a "maleta_produto"): o que chegou em cada maleta.
-- Maleta N:N Produto, com atributos próprios (quantidade e custo daquela remessa).
-- ---------------------------------------------------------------------
CREATE TABLE maleta_itens (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    maleta_id    BIGINT        NOT NULL REFERENCES maletas  (id) ON DELETE RESTRICT,
    produto_id   BIGINT        NOT NULL REFERENCES produtos (id) ON DELETE RESTRICT,
    quantidade   INTEGER       NOT NULL,          -- quantidade RECEBIDA nesta maleta
    preco_custo  NUMERIC(12,2) NOT NULL,          -- custo desta remessa
    codigo_fornecedor     VARCHAR(40),            -- como veio na lista da loja (para o acerto da maleta)
    descricao_fornecedor  TEXT,                   -- idem
    criado_em    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_maleta_itens_maleta_produto UNIQUE (maleta_id, produto_id),
    -- alvo da FK composta usada em pecas, itens_venda e movimentacoes_estoque
    CONSTRAINT uq_maleta_itens_id_produto     UNIQUE (id, produto_id),
    CONSTRAINT ck_maleta_itens_quantidade     CHECK (quantidade > 0),
    CONSTRAINT ck_maleta_itens_preco_custo    CHECK (preco_custo >= 0)
);
-- (maleta_id, produto_id) já indexa maleta_id; produto_id precisa do seu.
CREATE INDEX ix_maleta_itens_produto ON maleta_itens (produto_id);

-- ---------------------------------------------------------------------
-- pecas  = cada UNIDADE física, com etiqueta própria.
-- Produto é o modelo (C0001 = gargantilha veneziana); peça é a unidade (C0001-01).
-- Etiqueta = código do produto + número da peça: C0001-01, C0001-02, ... C0001-100.
--   O código da etiqueta NÃO é guardado: vem de vw_pecas / vw_busca_peca. Assim,
--   se o produto mudar de categoria (C0001 -> K0001), a etiqueta antiga ainda acha a peça.
-- numero é preenchido pela trigger trg_pecas_protecao (Parte 3): o back nunca envia.
-- Situação (disponível, vendida, perdida, devolvida) também não é coluna: vem da
-- última movimentação da peça (vw_pecas).
-- Na entrada da maleta, o back cria uma peça por unidade recebida, cada uma com a
-- sua movimentação ENTRADA (conferido no COMMIT).
-- ---------------------------------------------------------------------
CREATE TABLE pecas (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id      BIGINT      NOT NULL REFERENCES produtos (id) ON DELETE RESTRICT,
    maleta_item_id  BIGINT      NOT NULL,       -- de qual maleta (remessa) a peça veio
    numero          INTEGER     NOT NULL,       -- 1, 2, 3... contador próprio de cada produto
    criado_em       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_pecas_produto_numero  UNIQUE (produto_id, numero),
    -- alvo da FK composta usada em itens_venda e movimentacoes_estoque
    CONSTRAINT uq_pecas_id_maleta_item  UNIQUE (id, maleta_item_id),
    CONSTRAINT ck_pecas_numero          CHECK (numero > 0),
    -- garante que a maleta de origem é do MESMO produto da peça
    CONSTRAINT fk_pecas_maleta_item FOREIGN KEY (maleta_item_id, produto_id)
        REFERENCES maleta_itens (id, produto_id) ON DELETE RESTRICT
);
-- (produto_id, numero) já indexa produto_id.
CREATE INDEX ix_pecas_maleta_item ON pecas (maleta_item_id);

-- ---------------------------------------------------------------------
-- vendas
-- O fluxo de venda grava direto como FINALIZADA (POST /vendas/confirmar).
-- RASCUNHO fica disponível para um uso futuro (ex.: peças levadas em condicional).
-- valor_total é coluna GERADA: nunca diverge de produtos + acréscimo - desconto.
-- acrescimo guarda os +10% separados, para o lucro continuar mostrando o preço real da joia.
-- ---------------------------------------------------------------------
CREATE TABLE vendas (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id           BIGINT        NOT NULL REFERENCES clientes (id) ON DELETE RESTRICT,
    usuario_id           BIGINT        NOT NULL REFERENCES usuarios (id) ON DELETE RESTRICT,
    data_venda           DATE          NOT NULL DEFAULT CURRENT_DATE,
    valor_produtos       NUMERIC(12,2) NOT NULL DEFAULT 0,       -- = soma dos subtotais dos itens
    desconto             NUMERIC(12,2) NOT NULL DEFAULT 0,
    acrescimo            NUMERIC(12,2) NOT NULL DEFAULT 0,       -- ex.: +10% calculado pelo back na prévia
    valor_total          NUMERIC(12,2) GENERATED ALWAYS AS (valor_produtos + acrescimo - desconto) STORED,
    status               VARCHAR(10)   NOT NULL DEFAULT 'RASCUNHO',
    finalizada_em        TIMESTAMPTZ,
    cancelada_em         TIMESTAMPTZ,
    motivo_cancelamento  TEXT,
    observacoes          TEXT,
    criado_em            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    atualizado_em        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_vendas_valor_produtos CHECK (valor_produtos >= 0),
    CONSTRAINT ck_vendas_desconto       CHECK (desconto >= 0 AND desconto <= valor_produtos),
    CONSTRAINT ck_vendas_acrescimo      CHECK (acrescimo >= 0),
    CONSTRAINT ck_vendas_status         CHECK (status IN ('RASCUNHO', 'FINALIZADA', 'CANCELADA')),
    CONSTRAINT ck_vendas_finalizada     CHECK (status = 'RASCUNHO' OR finalizada_em IS NOT NULL),
    CONSTRAINT ck_vendas_cancelada      CHECK ((status = 'CANCELADA') = (cancelada_em IS NOT NULL))
);
CREATE INDEX ix_vendas_cliente    ON vendas (cliente_id);
CREATE INDEX ix_vendas_usuario    ON vendas (usuario_id);
CREATE INDEX ix_vendas_data_venda ON vendas (data_venda) WHERE status = 'FINALIZADA';

-- ---------------------------------------------------------------------
-- itens_venda  (preço congelado no momento da venda)
-- UMA LINHA POR PEÇA: vender 3 gargantilhas = 3 linhas, cada uma com a sua etiqueta.
-- A peça vem da etiqueta lida. Se a vendedora digitar só o modelo (C0001), o back
-- escolhe a peça DISPONIVEL da maleta mais antiga (FIFO, ver vw_pecas).
-- maleta_item_id é a maleta da peça (FK composta garante): o dashboard por maleta
-- depende dele.
-- quantidade fica sempre 1; existe para subtotal e dashboards continuarem iguais.
-- ---------------------------------------------------------------------
CREATE TABLE itens_venda (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venda_id              BIGINT        NOT NULL REFERENCES vendas (id) ON DELETE CASCADE,  -- só rascunho pode ser apagado (Parte 3)
    produto_id            BIGINT        NOT NULL REFERENCES produtos (id) ON DELETE RESTRICT,
    maleta_item_id        BIGINT        NOT NULL,       -- de qual maleta saiu a peça
    peca_id               BIGINT        NOT NULL,       -- a unidade vendida (etiqueta C0001-01)
    quantidade            INTEGER       NOT NULL DEFAULT 1,
    preco_unitario        NUMERIC(12,2) NOT NULL,       -- snapshot do preço de venda
    preco_custo_unitario  NUMERIC(12,2) NOT NULL,       -- snapshot do custo (para lucro)
    subtotal              NUMERIC(12,2) GENERATED ALWAYS AS (quantidade * preco_unitario) STORED,
    CONSTRAINT ck_itens_venda_quantidade CHECK (quantidade = 1),
    CONSTRAINT ck_itens_venda_preco      CHECK (preco_unitario >= 0),
    CONSTRAINT ck_itens_venda_custo      CHECK (preco_custo_unitario >= 0),
    CONSTRAINT uq_itens_venda_peca       UNIQUE (venda_id, peca_id),
    -- garante que o maleta_item é do MESMO produto do item
    CONSTRAINT fk_itens_venda_maleta_item FOREIGN KEY (maleta_item_id, produto_id)
        REFERENCES maleta_itens (id, produto_id) ON DELETE RESTRICT,
    -- garante que a peça é dessa maleta (e, pela FK acima, desse produto)
    CONSTRAINT fk_itens_venda_peca FOREIGN KEY (peca_id, maleta_item_id)
        REFERENCES pecas (id, maleta_item_id) ON DELETE RESTRICT
);
-- (venda_id, peca_id) já indexa venda_id.
CREATE INDEX ix_itens_venda_produto     ON itens_venda (produto_id);
CREATE INDEX ix_itens_venda_maleta_item ON itens_venda (maleta_item_id);
CREATE INDEX ix_itens_venda_peca        ON itens_venda (peca_id);

-- ---------------------------------------------------------------------
-- parcelas  (valor ESPERADO)
-- status só guarda o que NÃO dá pra calcular: ATIVA ou CANCELADA.
-- PENDENTE / PARCIAL / PAGA / ATRASADA são calculados na vw_saldo_parcelas.
-- Venda à vista = 1 parcela com vencimento na data da venda.
-- ---------------------------------------------------------------------
CREATE TABLE parcelas (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venda_id         BIGINT        NOT NULL REFERENCES vendas (id) ON DELETE CASCADE,
    numero_parcela   SMALLINT      NOT NULL,
    valor            NUMERIC(12,2) NOT NULL,
    data_vencimento  DATE          NOT NULL,
    status           VARCHAR(10)   NOT NULL DEFAULT 'ATIVA',
    criado_em        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    atualizado_em    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_parcelas_venda_numero UNIQUE (venda_id, numero_parcela),  -- também serve de índice p/ venda_id
    CONSTRAINT ck_parcelas_numero       CHECK (numero_parcela > 0),
    CONSTRAINT ck_parcelas_valor        CHECK (valor > 0),
    CONSTRAINT ck_parcelas_status       CHECK (status IN ('ATIVA', 'CANCELADA'))
);
-- a consulta mais frequente do sistema: parcelas ativas por vencimento
CREATE INDEX ix_parcelas_vencimento_ativas ON parcelas (data_vencimento) WHERE status = 'ATIVA';

-- ---------------------------------------------------------------------
-- pagamentos  (valor RECEBIDO). Nunca apagar: estornar.
-- Pagamento à vista entra na mesma transação do /vendas/confirmar.
-- ---------------------------------------------------------------------
CREATE TABLE pagamentos (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parcela_id            BIGINT        NOT NULL REFERENCES parcelas (id) ON DELETE RESTRICT,
    usuario_id            BIGINT        NOT NULL REFERENCES usuarios (id) ON DELETE RESTRICT,
    valor                 NUMERIC(12,2) NOT NULL,
    data_pagamento        DATE          NOT NULL DEFAULT CURRENT_DATE,
    forma_pagamento       VARCHAR(15)   NOT NULL,
    observacao            TEXT,
    estornado             BOOLEAN       NOT NULL DEFAULT FALSE,
    estornado_em          TIMESTAMPTZ,
    estornado_por         BIGINT        REFERENCES usuarios (id) ON DELETE RESTRICT,
    motivo_estorno        TEXT,
    criado_em             TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_pagamentos_valor   CHECK (valor > 0),
    CONSTRAINT ck_pagamentos_forma   CHECK (forma_pagamento IN ('PIX', 'DINHEIRO', 'CARTAO', 'TRANSFERENCIA', 'OUTRO')),
    CONSTRAINT ck_pagamentos_estorno CHECK (estornado = (estornado_em IS NOT NULL)
                                            AND (NOT estornado OR estornado_por IS NOT NULL))
);
-- soma de pagamentos válidos por parcela sem ler a tabela (index-only scan)
CREATE INDEX ix_pagamentos_parcela_validos ON pagamentos (parcela_id) INCLUDE (valor, data_pagamento) WHERE NOT estornado;
CREATE INDEX ix_pagamentos_data            ON pagamentos (data_pagamento) WHERE NOT estornado;
CREATE INDEX ix_pagamentos_usuario         ON pagamentos (usuario_id);

-- ---------------------------------------------------------------------
-- movimentacoes_estoque  (livro-razão: só INSERT)
-- UMA LINHA POR PEÇA, quantidade COM SINAL: +1 entrada, -1 venda, -1 perda.
-- Chegaram 3 gargantilhas = 3 ENTRADAs, uma para cada etiqueta.
-- estoque_anterior/posterior continuam sendo do PRODUTO (soma de todas as peças).
-- AJUSTE (+1) serve só para trazer de volta uma peça marcada como PERDA ou
-- DEVOLUCAO_FORNECEDOR (lançamento errado, peça encontrada) — Parte 3.
-- ---------------------------------------------------------------------
CREATE TABLE movimentacoes_estoque (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id         BIGINT      NOT NULL REFERENCES produtos (id) ON DELETE RESTRICT,
    maleta_item_id     BIGINT      NOT NULL,
    peca_id            BIGINT      NOT NULL,
    venda_id           BIGINT      REFERENCES vendas   (id) ON DELETE RESTRICT,
    usuario_id         BIGINT      NOT NULL REFERENCES usuarios (id) ON DELETE RESTRICT,
    tipo               VARCHAR(20) NOT NULL,
    quantidade         INTEGER     NOT NULL,
    estoque_anterior   INTEGER     NOT NULL,
    estoque_posterior  INTEGER     NOT NULL,
    observacao         TEXT,
    criado_em          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_mov_maleta_item FOREIGN KEY (maleta_item_id, produto_id)
        REFERENCES maleta_itens (id, produto_id) ON DELETE RESTRICT,
    -- garante que a peça é dessa maleta (e, pela FK acima, desse produto)
    CONSTRAINT fk_mov_peca FOREIGN KEY (peca_id, maleta_item_id)
        REFERENCES pecas (id, maleta_item_id) ON DELETE RESTRICT,
    CONSTRAINT ck_mov_tipo CHECK (tipo IN ('ENTRADA', 'VENDA', 'CANCELAMENTO_VENDA',
                                           'DEVOLUCAO_CLIENTE', 'DEVOLUCAO_FORNECEDOR', 'PERDA', 'AJUSTE')),
    CONSTRAINT ck_mov_quantidade CHECK (quantidade IN (-1, 1)),
    CONSTRAINT ck_mov_sinal CHECK (
           (tipo IN ('ENTRADA', 'CANCELAMENTO_VENDA', 'DEVOLUCAO_CLIENTE', 'AJUSTE') AND quantidade > 0)
        OR (tipo IN ('VENDA', 'PERDA', 'DEVOLUCAO_FORNECEDOR')                     AND quantidade < 0)),
    CONSTRAINT ck_mov_venda_obrigatoria CHECK (
        tipo NOT IN ('VENDA', 'CANCELAMENTO_VENDA', 'DEVOLUCAO_CLIENTE') OR venda_id IS NOT NULL),
    CONSTRAINT ck_mov_saldos CHECK (
        estoque_anterior >= 0 AND estoque_posterior >= 0
        AND estoque_posterior = estoque_anterior + quantidade),
    CONSTRAINT ck_mov_ajuste_com_motivo CHECK (tipo <> 'AJUSTE' OR btrim(coalesce(observacao, '')) <> '')
);
CREATE INDEX ix_mov_produto_data  ON movimentacoes_estoque (produto_id, criado_em);
CREATE INDEX ix_mov_criado_em     ON movimentacoes_estoque (criado_em);
CREATE INDEX ix_mov_venda         ON movimentacoes_estoque (venda_id)       WHERE venda_id IS NOT NULL;
CREATE INDEX ix_mov_maleta_item   ON movimentacoes_estoque (maleta_item_id);
-- última movimentação de cada peça (situação em vw_pecas e trava em trg_mov_validar)
CREATE INDEX ix_mov_peca          ON movimentacoes_estoque (peca_id, id);
CREATE INDEX ix_mov_usuario       ON movimentacoes_estoque (usuario_id);

-- ---------------------------------------------------------------------
-- cobrancas  (fase 1.5 — histórico de contatos: "cobrei, prometeu pagar dia 10")
-- ---------------------------------------------------------------------
CREATE TABLE cobrancas (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id       BIGINT        NOT NULL REFERENCES clientes (id) ON DELETE RESTRICT,
