-- 3.2 Venda: só rascunho pode ser apagada; status não "volta"
CREATE FUNCTION fn_vendas_protecao() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        IF OLD.status <> 'RASCUNHO' THEN
            RAISE EXCEPTION 'Venda % está % e não pode ser apagada (use cancelamento).', OLD.id, OLD.status;
        END IF;
        RETURN OLD;
    END IF;
    IF OLD.status = 'CANCELADA' AND NEW.status <> 'CANCELADA' THEN
        RAISE EXCEPTION 'Venda % cancelada não pode ser reaberta.', OLD.id;
    END IF;
    IF OLD.status = 'FINALIZADA' AND NEW.status = 'RASCUNHO' THEN
        RAISE EXCEPTION 'Venda % finalizada não pode voltar a rascunho.', OLD.id;
    END IF;
    -- "cancelar só sem pagamento válido" é conferido no COMMIT (fn_validar_venda, 3.3).
    -- Aqui, no UPDATE, dependeria da ordem em que o Hibernate manda os comandos.
    IF OLD.status = 'FINALIZADA' AND NEW.cliente_id <> OLD.cliente_id THEN
        RAISE EXCEPTION 'Não é permitido trocar o cliente de uma venda finalizada.';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_vendas_protecao BEFORE UPDATE OR DELETE ON vendas
    FOR EACH ROW EXECUTE FUNCTION fn_vendas_protecao();

-- 3.3 Conferido no COMMIT:
--     venda FINALIZADA fecha a conta: >= 1 item, soma dos itens = valor_produtos,
--       soma das parcelas ativas = valor_total, e cada peça vendida tem a sua
--       baixa de estoque (VENDA) nesta venda, e vice-versa;
--     venda CANCELADA não fica com pagamento válido (estorne antes) nem com
--       peça ainda marcada como vendida por ela (devolva ao estoque).
CREATE FUNCTION fn_validar_venda(p_venda_id BIGINT) RETURNS void LANGUAGE plpgsql AS $$
DECLARE
    v           vendas%ROWTYPE;
    qtd_itens   INTEGER;
    soma_itens  NUMERIC;
    soma_parc   NUMERIC;
BEGIN
    SELECT * INTO v FROM vendas WHERE id = p_venda_id;
    IF NOT FOUND THEN RETURN; END IF;

    IF v.status = 'CANCELADA' THEN
        IF EXISTS (SELECT 1 FROM pagamentos pa JOIN parcelas p ON p.id = pa.parcela_id
                   WHERE p.venda_id = p_venda_id AND NOT pa.estornado) THEN
            RAISE EXCEPTION 'Venda % tem pagamentos válidos; estorne-os antes de cancelar.', p_venda_id;
        END IF;
        -- olha só as peças desta venda: a última movimentação de cada uma não pode ser a VENDA dela
        IF EXISTS (SELECT 1
                   FROM (SELECT DISTINCT peca_id FROM movimentacoes_estoque
                         WHERE venda_id = p_venda_id AND tipo = 'VENDA') x
                   CROSS JOIN LATERAL (SELECT m.tipo, m.venda_id FROM movimentacoes_estoque m
                                       WHERE m.peca_id = x.peca_id
                                       ORDER BY m.id DESC LIMIT 1) u
                   WHERE u.tipo = 'VENDA' AND u.venda_id = p_venda_id) THEN
            RAISE EXCEPTION 'Venda % cancelada ainda tem peça marcada como vendida; devolva as peças ao estoque (CANCELAMENTO_VENDA).', p_venda_id;
        END IF;
        RETURN;
    END IF;

    -- devolução por cancelamento só existe em venda CANCELADA (senão a peça volta
    -- ao estoque e a cliente continua sendo cobrada)
    IF EXISTS (SELECT 1 FROM movimentacoes_estoque
               WHERE venda_id = p_venda_id AND tipo = 'CANCELAMENTO_VENDA') THEN
        RAISE EXCEPTION 'Venda % tem CANCELAMENTO_VENDA mas está %; mude o status para CANCELADA.', p_venda_id, v.status;
    END IF;

    -- rascunho não mexe no estoque (senão a peça fica presa como vendida)
    IF v.status = 'RASCUNHO' THEN
        IF EXISTS (SELECT 1 FROM movimentacoes_estoque WHERE venda_id = p_venda_id) THEN
            RAISE EXCEPTION 'Venda % é RASCUNHO e não pode ter movimentação de estoque.', p_venda_id;
        END IF;
        RETURN;
    END IF;

    IF v.status <> 'FINALIZADA' THEN RETURN; END IF;

    SELECT COUNT(*), COALESCE(SUM(subtotal), 0) INTO qtd_itens, soma_itens
    FROM itens_venda WHERE venda_id = p_venda_id;
    IF qtd_itens = 0 THEN
        RAISE EXCEPTION 'Venda % finalizada sem itens.', p_venda_id;
    END IF;
    IF soma_itens <> v.valor_produtos THEN
        RAISE EXCEPTION 'Venda %: valor_produtos (%) difere da soma dos itens (%).', p_venda_id, v.valor_produtos, soma_itens;
    END IF;

    SELECT COALESCE(SUM(valor), 0) INTO soma_parc
    FROM parcelas WHERE venda_id = p_venda_id AND status = 'ATIVA';
    IF soma_parc <> v.valor_total THEN
        RAISE EXCEPTION 'Venda %: parcelas ativas somam % mas o total é %.', p_venda_id, soma_parc, v.valor_total;
    END IF;

    IF EXISTS (SELECT 1 FROM itens_venda iv
               WHERE iv.venda_id = p_venda_id
                 AND NOT EXISTS (SELECT 1 FROM movimentacoes_estoque m
                                 WHERE m.venda_id = p_venda_id AND m.tipo = 'VENDA'
                                   AND m.peca_id = iv.peca_id))
       OR EXISTS (SELECT 1 FROM movimentacoes_estoque m
                  WHERE m.venda_id = p_venda_id AND m.tipo = 'VENDA'
                    AND NOT EXISTS (SELECT 1 FROM itens_venda iv
                                    WHERE iv.venda_id = p_venda_id AND iv.peca_id = m.peca_id)) THEN
        RAISE EXCEPTION 'Venda %: as peças dos itens não batem com as baixas de estoque (VENDA).', p_venda_id;
    END IF;
END $$;

CREATE FUNCTION fn_trg_validar_venda() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_TABLE_NAME = 'vendas' THEN
        PERFORM fn_validar_venda(NEW.id);
    ELSE
        IF TG_OP IN ('INSERT', 'UPDATE') THEN PERFORM fn_validar_venda(NEW.venda_id); END IF;
        IF TG_OP IN ('UPDATE', 'DELETE') THEN PERFORM fn_validar_venda(OLD.venda_id); END IF;
    END IF;
    RETURN NULL;
END $$;

CREATE CONSTRAINT TRIGGER trg_vendas_validar AFTER INSERT OR UPDATE ON vendas
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION fn_trg_validar_venda();
CREATE CONSTRAINT TRIGGER trg_itens_venda_validar AFTER INSERT OR UPDATE OR DELETE ON itens_venda
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION fn_trg_validar_venda();
CREATE CONSTRAINT TRIGGER trg_parcelas_validar AFTER INSERT OR UPDATE OR DELETE ON parcelas
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION fn_trg_validar_venda();
CREATE CONSTRAINT TRIGGER trg_mov_validar_venda AFTER INSERT ON movimentacoes_estoque
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW
    WHEN (NEW.venda_id IS NOT NULL) EXECUTE FUNCTION fn_trg_validar_venda();

-- 3.4 Pagamento: parcela ativa de venda finalizada, sem pagar a mais; nunca apagar
CREATE FUNCTION fn_pagamentos_protecao() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    p          parcelas%ROWTYPE;
    v_venda_id BIGINT;
    st_venda   VARCHAR;
    ja_pago    NUMERIC;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Pagamentos não são apagados; registre um estorno.';
    END IF;

    IF TG_OP = 'UPDATE' THEN
        IF OLD.estornado AND NOT NEW.estornado THEN
            RAISE EXCEPTION 'Estorno não pode ser desfeito; lance um novo pagamento.';
        END IF;
        IF (NEW.parcela_id, NEW.valor, NEW.data_pagamento, NEW.forma_pagamento, NEW.usuario_id)
           IS DISTINCT FROM
           (OLD.parcela_id, OLD.valor, OLD.data_pagamento, OLD.forma_pagamento, OLD.usuario_id) THEN
            RAISE EXCEPTION 'Pagamento não pode ser alterado; estorne e lance outro.';
        END IF;
        RETURN NEW;
    END IF;

    -- INSERT: trava a venda primeiro (um cancelamento simultâneo espera, e vice-versa)...
    SELECT venda_id INTO v_venda_id FROM parcelas WHERE id = NEW.parcela_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Parcela % não existe.', NEW.parcela_id;
    END IF;
    SELECT status INTO st_venda FROM vendas WHERE id = v_venda_id FOR SHARE;
    -- ...depois a parcela (dois pagamentos simultâneos não ultrapassam o valor)
    SELECT * INTO p FROM parcelas WHERE id = NEW.parcela_id FOR UPDATE;

    IF p.status <> 'ATIVA' OR st_venda <> 'FINALIZADA' THEN
        RAISE EXCEPTION 'Parcela % não aceita pagamento (parcela %, venda %).', p.id, p.status, st_venda;
    END IF;
    IF NEW.estornado THEN
        RAISE EXCEPTION 'Pagamento não pode nascer estornado.';
    END IF;
    SELECT COALESCE(SUM(valor), 0) INTO ja_pago
    FROM pagamentos WHERE parcela_id = p.id AND NOT estornado;
    IF ja_pago + NEW.valor > p.valor THEN
        RAISE EXCEPTION 'Pagamento de % excede o saldo da parcela % (saldo %).', NEW.valor, p.id, p.valor - ja_pago;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_pagamentos_protecao BEFORE INSERT OR UPDATE OR DELETE ON pagamentos
    FOR EACH ROW EXECUTE FUNCTION fn_pagamentos_protecao();

-- 3.5 Parcela: não cancelar nem reduzir abaixo do que já foi pago
CREATE FUNCTION fn_parcelas_protecao() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE ja_pago NUMERIC;
BEGIN
    SELECT COALESCE(SUM(valor), 0) INTO ja_pago
    FROM pagamentos WHERE parcela_id = OLD.id AND NOT estornado;
    IF TG_OP = 'DELETE' THEN
        IF ja_pago > 0 OR EXISTS (SELECT 1 FROM pagamentos WHERE parcela_id = OLD.id) THEN
            RAISE EXCEPTION 'Parcela % tem pagamentos e não pode ser apagada.', OLD.id;
        END IF;
        RETURN OLD;
    END IF;
    IF NEW.status = 'CANCELADA' AND OLD.status = 'ATIVA' AND ja_pago > 0 THEN
        RAISE EXCEPTION 'Parcela % tem % pago; estorne antes de cancelar.', OLD.id, ja_pago;
    END IF;
    IF NEW.valor < ja_pago THEN
        RAISE EXCEPTION 'Parcela % não pode valer menos que o já pago (%).', OLD.id, ja_pago;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_parcelas_protecao BEFORE UPDATE OR DELETE ON parcelas
    FOR EACH ROW EXECUTE FUNCTION fn_parcelas_protecao();

