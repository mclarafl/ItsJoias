-- 3.6b Cada peça segue um caminho válido, olhando a última movimentação dela:
--      ENTRADA                      -> só uma vez, a primeira de todas
--      VENDA, PERDA, DEVOL_FORNEC.  -> só se a peça está DISPONIVEL
--      CANCELAMENTO_VENDA, DEVOL_CLIENTE -> só se a peça está VENDIDA nesta mesma venda
--      AJUSTE (+1)                  -> só traz de volta peça PERDIDA ou DEVOLVIDA
--      Isso impede vender a mesma peça duas vezes, devolver em dobro e saldo
--      negativo por maleta.
--      Trava o PRODUTO (a mesma trava do travarProdutos do back e da trigger de
--      peças): duas sessões nunca mexem nas peças do mesmo produto ao mesmo tempo,
--      e a ordem das travas é sempre a mesma, sem deadlock com a venda.
--      O id da movimentação é sorteado DEPOIS da trava: a "última movimentação"
--      da peça é a de maior id, e um id sorteado antes de esperar a trava ficaria
--      menor que o de quem passou na frente.
--      Não exige "venda já CANCELADA": o Hibernate grava a movimentação antes
--      do UPDATE da venda, e isso recusaria um cancelamento correto.
CREATE FUNCTION fn_mov_validar() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_tem_ult   BOOLEAN;
    v_ult_tipo  VARCHAR;
    v_ult_venda BIGINT;
BEGIN
    PERFORM 1 FROM produtos WHERE id = NEW.produto_id FOR NO KEY UPDATE;
    NEW.id := nextval(pg_get_serial_sequence('movimentacoes_estoque', 'id'));

    SELECT tipo, venda_id INTO v_ult_tipo, v_ult_venda
    FROM movimentacoes_estoque
    WHERE peca_id = NEW.peca_id
    ORDER BY id DESC
    LIMIT 1;
    v_tem_ult := FOUND;

    IF NEW.tipo = 'ENTRADA' THEN
        IF v_tem_ult THEN
            RAISE EXCEPTION 'Peça % já deu entrada no estoque.', NEW.peca_id;
        END IF;
    ELSIF NOT v_tem_ult THEN
        RAISE EXCEPTION 'Peça % ainda não deu entrada no estoque.', NEW.peca_id;
    ELSIF NEW.tipo IN ('VENDA', 'PERDA', 'DEVOLUCAO_FORNECEDOR') THEN
        IF v_ult_tipo IN ('VENDA', 'PERDA', 'DEVOLUCAO_FORNECEDOR') THEN
            RAISE EXCEPTION 'Peça % não está disponível (último registro: %).', NEW.peca_id, v_ult_tipo;
        END IF;
    ELSIF NEW.tipo IN ('CANCELAMENTO_VENDA', 'DEVOLUCAO_CLIENTE') THEN
        IF v_ult_tipo <> 'VENDA' OR v_ult_venda IS DISTINCT FROM NEW.venda_id THEN
            RAISE EXCEPTION 'Peça % não está vendida na venda %; não há o que devolver.', NEW.peca_id, NEW.venda_id;
        END IF;
    ELSIF NEW.tipo = 'AJUSTE' THEN
        IF v_ult_tipo NOT IN ('PERDA', 'DEVOLUCAO_FORNECEDOR') THEN
            RAISE EXCEPTION 'AJUSTE só traz de volta peça perdida ou devolvida; a peça % não está (último registro: %).', NEW.peca_id, v_ult_tipo;
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_mov_validar BEFORE INSERT ON movimentacoes_estoque
    FOR EACH ROW EXECUTE FUNCTION fn_mov_validar();

-- 3.6c Peças: número da etiqueta gerado pelo banco; peça nunca é apagada nem alterada
--      INSERT: numero = próximo número daquele produto (o back nunca envia).
--      Trava o produto: duas entradas simultâneas nunca pegam o mesmo número.
CREATE FUNCTION fn_pecas_protecao() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Peças não são apagadas; registre PERDA ou DEVOLUCAO_FORNECEDOR.';
    END IF;
    IF TG_OP = 'UPDATE' THEN
        IF (NEW.produto_id, NEW.maleta_item_id, NEW.numero)
           IS DISTINCT FROM (OLD.produto_id, OLD.maleta_item_id, OLD.numero) THEN
            RAISE EXCEPTION 'Peça % não pode ser alterada (a etiqueta pode já estar impressa).', OLD.id;
        END IF;
        RETURN NEW;
    END IF;
    PERFORM 1 FROM produtos WHERE id = NEW.produto_id FOR NO KEY UPDATE;
    NEW.numero := (SELECT COALESCE(MAX(numero), 0) + 1 FROM pecas WHERE produto_id = NEW.produto_id);
    RETURN NEW;
END $$;
CREATE TRIGGER trg_pecas_protecao BEFORE INSERT OR UPDATE OR DELETE ON pecas
    FOR EACH ROW EXECUTE FUNCTION fn_pecas_protecao();

-- 3.6d Entrada de maleta fecha a conta no COMMIT: cada item de maleta tem
--      exatamente "quantidade" peças, e cada peça tem a sua ENTRADA.
CREATE FUNCTION fn_trg_conferir_maleta_item() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_id     BIGINT;
    v_qtd    INTEGER;
    v_pecas  INTEGER;
BEGIN
    IF TG_TABLE_NAME = 'pecas' THEN v_id := NEW.maleta_item_id; ELSE v_id := NEW.id; END IF;
    SELECT quantidade INTO v_qtd FROM maleta_itens WHERE id = v_id;
    SELECT COUNT(*) INTO v_pecas FROM pecas WHERE maleta_item_id = v_id;
    IF v_pecas <> v_qtd THEN
        RAISE EXCEPTION 'Item de maleta %: chegaram % peça(s), mas há % etiqueta(s) cadastrada(s).', v_id, v_qtd, v_pecas;
    END IF;
    IF EXISTS (SELECT 1 FROM pecas pc
               WHERE pc.maleta_item_id = v_id
                 AND NOT EXISTS (SELECT 1 FROM movimentacoes_estoque m
                                 WHERE m.peca_id = pc.id AND m.tipo = 'ENTRADA')) THEN
        RAISE EXCEPTION 'Item de maleta %: há peça sem movimentação de ENTRADA.', v_id;
    END IF;
    RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER trg_maleta_itens_conferir AFTER INSERT OR UPDATE ON maleta_itens
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION fn_trg_conferir_maleta_item();
CREATE CONSTRAINT TRIGGER trg_pecas_conferir AFTER INSERT ON pecas
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION fn_trg_conferir_maleta_item();

-- 3.7 Código interno do produto: prefixo da categoria + contador da categoria
--     INSERT: sempre gera (o back nunca envia o código).
--     UPDATE trocando a categoria: gera código novo e guarda o antigo no histórico.
--     UPDATE do código "na mão": proibido.
CREATE FUNCTION fn_produtos_codigo() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_prefixo  VARCHAR;
    v_numero   INTEGER;
BEGIN
    IF TG_OP = 'INSERT' OR NEW.categoria_id IS DISTINCT FROM OLD.categoria_id THEN
        -- o UPDATE trava a linha da categoria: dois cadastros simultâneos nunca pegam o mesmo número
        UPDATE categorias
           SET proximo_numero = proximo_numero + 1
         WHERE id = NEW.categoria_id
        RETURNING prefixo, proximo_numero - 1 INTO v_prefixo, v_numero;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Categoria % não existe.', NEW.categoria_id;
        END IF;

        IF TG_OP = 'UPDATE' THEN
            INSERT INTO produto_codigos_historico (produto_id, codigo) VALUES (OLD.id, OLD.codigo);
        END IF;

        -- C0001 ... C9999, C10000 (nunca corta dígitos)
        NEW.codigo := v_prefixo || lpad(v_numero::text, greatest(4, length(v_numero::text)), '0');
    ELSIF NEW.codigo IS DISTINCT FROM OLD.codigo THEN
        RAISE EXCEPTION 'O código do produto é gerado pelo sistema; para mudar, troque a categoria.';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_produtos_codigo BEFORE INSERT OR UPDATE ON produtos
    FOR EACH ROW EXECUTE FUNCTION fn_produtos_codigo();

-- 3.8 Prefixo da categoria não muda depois que já existem produtos com ele
--     (senão as etiquetas impressas deixam de bater com o sistema)
CREATE FUNCTION fn_categorias_protecao() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.prefixo <> OLD.prefixo AND OLD.proximo_numero > 1 THEN
        RAISE EXCEPTION 'Categoria % já gerou códigos com o prefixo %; ele não pode mudar.', OLD.nome, OLD.prefixo;
    END IF;
    IF NEW.proximo_numero < OLD.proximo_numero THEN
        RAISE EXCEPTION 'O contador de códigos não pode voltar (evita código repetido).';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_categorias_protecao BEFORE UPDATE ON categorias
    FOR EACH ROW EXECUTE FUNCTION fn_categorias_protecao();

